export type MessageKey = keyof typeof messages.en

export type TemplateValues = Record<string, string | number | undefined | null>

export function isSupportedLocale(value: string | undefined | null): value is SupportedLocale {
  return value === 'en' || value === 'zh'
}

export function normalizeLocale(value?: string | null): SupportedLocale | null {
  if (!value) return null
  const normalized = value.toLowerCase()
  if (normalized.startsWith('zh')) return 'zh'
  if (normalized.startsWith('en')) return 'en'
  return null
}

export function resolveInitialLocale({
  storedLocale,
  browserLocale,
  defaultLocale = DEFAULT_LOCALE
}: {
  storedLocale?: string | null
  browserLocale?: string | null
  defaultLocale?: SupportedLocale
} = {}): SupportedLocale {
  return normalizeLocale(storedLocale) || normalizeLocale(browserLocale) || defaultLocale
}

export function translate(locale: SupportedLocale, key: MessageKey, values: TemplateValues = {}) {
  const template = messages[locale][key] || messages[DEFAULT_LOCALE][key] || key
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? ''))
}

export function useI18n() {
  const [locale, setLocale] = useState<SupportedLocale>(DEFAULT_LOCALE)

  useEffect(() => {
    const nextLocale = resolveInitialLocale({
      storedLocale: window.localStorage.getItem(LOCALE_STORAGE_KEY),
      browserLocale: window.navigator.language
    })
    setLocale(nextLocale)
  }, [])

  useEffect(() => {
    window.localStorage.setItem(LOCALE_STORAGE_KEY, locale)
    document.documentElement.lang = locale === 'zh' ? 'zh-CN' : 'en'
  }, [locale])

  const t = useCallback((key: MessageKey, values?: TemplateValues) => translate(locale, key, values), [locale])
  const supportedLocales = useMemo(() => SUPPORTED_LOCALES, [])

  return {
    locale,
    setLocale,
    supportedLocales,
    t
  }
}
